	ld a, [wLoadedCardAtk + 1]
	ld b, a
	call Apply60PercentReduction
	ld a, c
	ld [wLoadedCardAtk + 0], a
	ld a, b
	ld [wLoadedCardAtk + 1], a
	ld a, [wLoadedCardDef + 0]
	ld c, a
	ld a, [wLoadedCardDef + 1]
	ld b, a
	call Apply60PercentReduction
	ld a, c
	ld [wLoadedCardDef + 0], a
	ld a, b
	ld [wLoadedCardDef + 1], a
	pop bc
	pop af
	ret

