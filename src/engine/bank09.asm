ApplyCardLevelBoost:
	push af
	push bc
	push hl
	call GetCardLevel
	ld b, $00
	ld c, a
	sla c
	ld hl, .Jumptable
	add hl, bc
	ld a, [hli]
	ld h, [hl]
	ld l, a
	call_hl
	pop hl
	pop bc
	pop af
	ret

