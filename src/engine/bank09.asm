Apply60PercentBoost:
	push af
	push de
	push hl

	ld h, b
	ld l, c

	; bc /= 10
	ld e, 4
.loop_div
	srl b
	rr c
	dec e
	jr nz, .loop_div

	; bc *= 2
	ld a, c
	add c
	daa
	ld c, a
	ld a, b
	adc b
	daa
	ld b, a

	; bc *= 3
	ld a, c
	add c
	daa
	ld e, a
	ld a, b
	adc b
	daa
	ld d, a
	ld a, e
	add c
	daa
	ld c, a
	ld a, d
	adc b
	daa
	ld b, a

	; bc += hl
	ld a, l
	add c
	daa
	ld c, a
	ld a, h
	adc b
	daa
	ld b, a

	pop hl
	pop de
	pop af
	ret

